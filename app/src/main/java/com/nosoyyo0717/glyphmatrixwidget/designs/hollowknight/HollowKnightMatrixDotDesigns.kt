fun getHollowKnightMatrixDotDesign(mobName: String, deviceModel: String): IntArray {
    if (deviceModel == "4aPro") {
        return when (mobName) {
            "Hollow Knight" -> IntArray(169) { 0 }
            else -> IntArray(169) { 0 }
        }
    } else if (deviceModel == "3"){
        return when (mobName) {
            "The Knight - 1" -> getTheKnight1()
            "The Knight - 2" -> getTheKnight2()
            "The Knight - 3" -> getTheknight3()
            "The Knight - 4" -> getTheknight4()
            "Title - 1" -> getHollowKnightTitle1()
            "Title - 2" -> getHollowKnightTitle2()
            else -> IntArray(625) { 0 }
        }
    }
    return IntArray(625) { 0 }
}
